// Generates ../colors_v2.go, the v2 scheme color table, from the URnetwork brand
// palette (the named stops in android app ui/theme/Color.kt; web aliases from the
// ur.xyz --brand-* variables).
// Usage: node gen_colors_v2.mjs
//
// Backgrounds are the two product surfaces (Black, Blue900). Foreground/spot are
// ordered pairs of the flagship brand accents with distinct color families, filtered
// for contrast against the background (WCAG ratio bg->fg >= 4.5, bg->spot >= 1.8).
// ProGold is deliberately excluded: it is reserved product-wide to mean Pro.
//
// The table entries are hsl because that is what the render engine consumes. The
// hsl values are computed so that hslColor.rgba() reproduces each brand hex exactly;
// this script verifies the round trip with the same arithmetic as the go code (js
// numbers are float64, so the check is bit-exact), and colors_v2_test.go verifies it
// again on the go side.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const genDir = dirname(fileURLToPath(import.meta.url));

// name, family, hex from android ui/theme/Color.kt
const black = { name: 'Black', family: 'neutral', hex: '101010' };
const blue900 = { name: 'Blue900', family: 'blue', hex: '1A1460' };
const backgrounds = [black, blue900];
const accents = [
	{ name: 'Pink300', family: 'pink', hex: 'ED8FFF' }, // --brand-ur
	{ name: 'Pink500', family: 'pink', hex: 'DC40F5' },
	{ name: 'Green300', family: 'green', hex: '87FB67' }, // --brand-usd
	{ name: 'Green500', family: 'green', hex: '31D70B' },
	{ name: 'Blue200', family: 'blue', hex: 'D6E6F4' }, // --brand-ui
	{ name: 'Blue400', family: 'blue', hex: '638BFC' },
	{ name: 'Blue500', family: 'blue', hex: '2A60FF' },
	{ name: 'Red400', family: 'red', hex: 'FF6C58' }, // --brand-burn
	{ name: 'Yellow200', family: 'yellow', hex: 'EFF7BB' },
	{ name: 'Yellow400', family: 'yellow', hex: 'E6EA23' },
	{ name: 'OffWhite', family: 'neutral', hex: 'F8F8F8' }, // --brand-white
];

const rgb = (c) => [0, 2, 4].map((i) => parseInt(c.hex.slice(i, i + 2), 16));

// exact inverse of hslColor.rgba for in-gamut values
const hsl = (c) => {
	const [ri, gi, bi] = rgb(c);
	const r = ri / 255, g = gi / 255, b = bi / 255;
	const max = Math.max(r, Math.max(g, b));
	const min = Math.min(r, Math.min(g, b));
	const l = (max + min) / 2;
	if (max === min) {
		return { h: 0, s: 0, l: l * 100 };
	}
	const d = max - min;
	const s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
	let h;
	if (max === r) {
		h = (g - b) / d;
		if (g < b) {
			h += 6;
		}
	} else if (max === g) {
		h = (b - r) / d + 2;
	} else {
		h = (r - g) / d + 4;
	}
	return { h: h * 60, s: s * 100, l: l * 100 };
};

// hslColor.rgba ported op for op, to verify the round trip
const hslToRgb = ({ h, s, l }) => {
	h = ((h % 360) + 360) % 360;
	s = s / 100;
	l = l / 100;
	const c = (1 - Math.abs(2 * l - 1)) * s;
	const hPrime = h / 60;
	const x = c * (1 - Math.abs((hPrime % 2) - 1));
	const m = l - c / 2;
	let r1, g1, b1;
	if (hPrime < 1) { [r1, g1, b1] = [c, x, 0]; }
	else if (hPrime < 2) { [r1, g1, b1] = [x, c, 0]; }
	else if (hPrime < 3) { [r1, g1, b1] = [0, c, x]; }
	else if (hPrime < 4) { [r1, g1, b1] = [0, x, c]; }
	else if (hPrime < 5) { [r1, g1, b1] = [x, 0, c]; }
	else { [r1, g1, b1] = [c, 0, x]; }
	return [r1, g1, b1].map((v) => Math.round(255 * (v + m)));
};

for (const c of [...backgrounds, ...accents]) {
	const got = hslToRgb(hsl(c));
	if (got.some((v, i) => v !== rgb(c)[i])) {
		throw new Error(`${c.name} #${c.hex} does not round trip: got ${got}`);
	}
}

// wcag relative luminance + contrast ratio
const luminance = (c) => {
	const lin = (v) => {
		const f = v / 255;
		return f <= 0.03928 ? f / 12.92 : Math.pow((f + 0.055) / 1.055, 2.4);
	};
	const [r, g, b] = rgb(c);
	return 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b);
};
const contrast = (a, b) => {
	let la = luminance(a), lb = luminance(b);
	if (la < lb) {
		[la, lb] = [lb, la];
	}
	return (la + 0.05) / (lb + 0.05);
};

const combos = [];
for (const bg of backgrounds) {
	for (const fg of accents) {
		if (fg.family === bg.family && bg.family !== 'neutral') continue;
		for (const spot of accents) {
			if (spot.name === fg.name || (spot.family === fg.family && spot.family !== 'neutral')) continue;
			if (spot.family === bg.family && bg.family !== 'neutral') continue;
			if (contrast(bg, fg) >= 4.5 && contrast(bg, spot) >= 1.8) {
				combos.push([bg, fg, spot]);
			}
		}
	}
}
if (combos.length !== 140) throw new Error(`unexpected table length ${combos.length}`);

// String(number) is the shortest round-trip decimal, and js numbers are float64, so
// the emitted literals parse to the same float64s in go
const fmt = (c) => {
	const { h, s, l } = hsl(c);
	return `{h: ${h}, s: ${s}, l: ${l}}`;
};

let out = `// Code generated by gen/gen_colors_v2.mjs; do not edit by hand.

package goidenticons

// colorCombinationsV2 are the pre-defined color palettes of the v2 scheme, generated
// from the URnetwork brand palette (android ui/theme/Color.kt). Backgrounds are the
// two product surfaces (Black, Blue900); foreground and spot are ordered pairs of the
// flagship brand accents with distinct color families, contrast filtered against the
// background. Each combination is [background, foreground, spot]. Hue is in degrees,
// saturation and lightness are percentages; every value reproduces its exact brand
// hex through hslColor.rgba (verified by the generator and by colors_v2_test.go).
var colorCombinationsV2 = [][3]hslColor{
`;
for (const combo of combos) {
	out += `\t{${combo.map(fmt).join(', ')}},\n`;
}
out += `}\n`;
writeFileSync(join(genDir, '../colors_v2.go'), out);
console.log('wrote colors_v2.go,', combos.length, 'combinations');
